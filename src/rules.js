'use strict';

const fs = require('fs');
const path = require('path');
const scanner = require('./scanner');

function summarizeFiles(files, limit) {
  const sorted = [...files].sort((a, b) => b.bytes - a.bytes).slice(0, limit);
  return sorted.map((f) => `- ${f.rel} (${(f.bytes / 1024).toFixed(1)} KB, ~${scanner.tokenEstimate(f.bytes)} tok)`).join('\n');
}

function generateRulesContent(files, tool) {
  const totalBytes = files.reduce((s, f) => s + f.bytes, 0);
  const totalTokens = scanner.tokenEstimate(totalBytes);
  const top = summarizeFiles(files, 25);

  const header = `# ${tool === 'cursor' ? '.cursorrules' : '.clauderules'} — generated by llm-context-diet

## Project context budget
- Files tracked: ${files.length}
- Total size: ${(totalBytes / 1024).toFixed(1)} KB
- Estimated tokens: ~${totalTokens}

## Rules for the assistant
1. Prefer minimal diffs. Never re-print whole files unless asked.
2. When suggesting code, output only changed lines with 3 lines of surrounding context.
3. Do not restate imports or type definitions already present in the file.
4. If a file exceeds 200 lines, ask to see only the relevant section.
5. Use the file map below to decide which files to request.
6. Never assume file contents — request the smallest slice first.
7. Summarize long explanations as bullet points, not paragraphs.
8. Skip boilerplate comments and license headers when reasoning.

## Heaviest files (avoid pasting whole files)
${top}

## Token-saving heuristics
- Reuse names from the map instead of restating them.
- Prefer function signatures over bodies when reviewing.
- When generating new files, default to < 100 lines.
`;

  return header;
}

function generate(files, rootPath, tool) {
  const written = [];
  if (tool === 'cursor' || tool === 'both') {
    const p = path.join(rootPath, '.cursorrules');
    fs.writeFileSync(p, generateRulesContent(files, 'cursor'), 'utf8');
    written.push(p);
  }
  if (tool === 'claude' || tool === 'both') {
    const p = path.join(rootPath, '.clauderules');
    fs.writeFileSync(p, generateRulesContent(files, 'claude'), 'utf8');
    written.push(p);
  }
  return { written, fileCount: files.length };
}

module.exports = { generate, generateRulesContent };